#!/usr/bin/env python3
"""Build the word list include from a frequency-ordered word list.

    python3 tools/gen_words.py [--packed] [budget_bytes] [out.asm]

Keeps the C64-themed words first, then the most common 5-12 letter
words from wordsrc/google-10000-english-no-swears.txt until the byte
budget is used up.

Plain (default, words.asm): each word is ASCII caps + a 0 byte.
--packed (words_xl.asm):    each letter is 5 bits (A=1 .. Z=26), each
                            word ends with a 0 symbol, bits MSB first.
                            Every 32-word block starts on a fresh byte.
"""
import sys

args = sys.argv[1:]
PACKED = "--packed" in args
args = [a for a in args if a != "--packed"]
BUDGET = int(args[0]) if args else 35000
OUT = args[1] if len(args) > 1 else ("words_xl.asm" if PACKED else "words.asm")

SRC = "wordsrc/google-10000-english-no-swears.txt"
MIN_LEN, MAX_LEN = 5, 12
GROUP = 32                  # index entry every 32 words (pick_word relies on this)

THEME = """COMMODORE ASSEMBLER COMPUTER KEYBOARD DISKDRIVE JOYSTICK RETRO PIXEL
SPRITE KERNAL DATASETTE CARTRIDGE BASIC RASTER CHIPTUNE DEMOSCENE""".split()

# web junk / abbreviations / names that rank high in the list but make bad puzzles
SKIP = set("""
HTTP HTTPS WWW HTML XHTML PHP JAVASCRIPT CSS RSS URL FAQ PDF DVD CGI
USB JPG GIF MPEG SQL XML ASP SEO ISBN
""".split())


def cost(w):
    """Bits a word takes, letters plus its terminator."""
    return (len(w) + 1) * (5 if PACKED else 8)


words, seen, used = [], set(), 0
def add(w):
    global used
    # +7 bits of slack per word covers the byte rounding at block ends
    if w in seen or w in SKIP or used + cost(w) + 7 > BUDGET * 8:
        return
    seen.add(w)
    words.append(w)
    used += cost(w)

for w in THEME:
    add(w)
for line in open(SRC):
    w = line.strip().upper()
    if w.isalpha() and w.isascii() and MIN_LEN <= len(w) <= MAX_LEN:
        add(w)

assert len(words) <= 8192, "pick_word's block maths needs < 8192 words"
groups = [words[i:i + GROUP] for i in range(0, len(words), GROUP)]


def pack(grp):
    """5-bit symbols, MSB first, padded to a whole byte."""
    bits = "".join(format(ord(c) - 64, "05b") for w in grp for c in w + "@")
    bits += "0" * (-len(bits) % 8)
    return [int(bits[i:i + 8], 2) for i in range(0, len(bits), 8)]


total = 0
with open(OUT, "w") as f:
    f.write("; GENERATED by tools/gen_words.py - do not edit by hand.\n")
    if PACKED:
        f.write("; 5-bit packed: A=1..Z=26, 0 ends a word, MSB first.\n")
    else:
        f.write("; Each word is plain ASCII caps, 0-terminated.\n")
    f.write("; widx_lo/widx_hi point at every 32nd word.\n\n")
    f.write("WORD_COUNT = %d\n\n" % len(words))
    for n in ("lo", "hi"):
        f.write("widx_%s:\n" % n)
        op = "<" if n == "lo" else ">"
        for i in range(0, len(groups), 8):
            f.write("    !byte " + ",".join("%swg%d" % (op, g) for g in range(i, min(i + 8, len(groups)))) + "\n")
    f.write("\nword_list:\n")
    for g, grp in enumerate(groups):
        f.write("wg%d:\n" % g)
        if PACKED:
            data = pack(grp)
            total += len(data)
            f.write("    ; " + " ".join(grp) + "\n")
            for i in range(0, len(data), 16):
                f.write("    !byte " + ",".join("$%02X" % b for b in data[i:i + 16]) + "\n")
        else:
            total += sum(len(w) + 1 for w in grp)
            for i in range(0, len(grp), 8):
                f.write("    !text " + ",0,".join('"%s"' % w for w in grp[i:i + 8]) + ",0\n")
print("%d words, %d bytes -> %s" % (len(words), total, OUT))
